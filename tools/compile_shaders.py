#!/usr/bin/env python3
"""Compile src/gfx/shaders/*.vert|*.frag to SPIR-V and embed them in
src/gfx/shaders_spv.h, which is committed so nobody else needs a shader
compiler. Needs glslangValidator (package glslang-tools)."""
import hashlib, os, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src", "gfx", "shaders")
OUT = os.path.join(ROOT, "src", "gfx", "shaders_spv.h")
# Extra builds of a shader with preprocessor definitions: name -> [(identifier, [defines])].
VARIANTS = {"ff.frag": [("ff_ps_frag", ["PIXEL_SHADER"])]}
# Shaders also embedded as source, for building at run time: name -> identifier
# (vsh.vert: src/gfx/vsh_spec.c adds each program's own run_spec; ff.frag: one draw setup
# as constants).
SOURCES = {"vsh.vert": "vsh_vert_src", "ff.frag": "ff_frag_src"}

def sources_hash():
    """The shader sources' hash, as CMakeLists.txt works it out to warn when
    shaders_spv.h is older than them: per file (sorted) "name:sha256\\n" of
    its text without carriage returns, then the sha256 of all of that."""
    listing = ""
    for name in sorted(os.listdir(SRC)):
        if name.endswith((".vert", ".frag")):
            text = open(os.path.join(SRC, name), "rb").read().replace(b"\r", b"")
            listing += f"{name}:{hashlib.sha256(text).hexdigest()}\n"
    return hashlib.sha256(listing.encode()).hexdigest()

def compile_one(path, defines):
    with tempfile.TemporaryDirectory() as tmp:
        spv = os.path.join(tmp, "out.spv")
        subprocess.run(["glslangValidator", "-V", "--target-env", "vulkan1.0"]
                       + ["-D" + d for d in defines] + ["-o", spv, path], check=True,
                       stdout=subprocess.DEVNULL)
        return open(spv, "rb").read()

def emit(lines, ident, data):
    lines.append(f"static const uint8_t {ident}_spv[{len(data)}] = {{")
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    lines.append("};")
    lines.append("")

def emit_source(lines, ident, text):
    lines.append(f"static const char {ident}[] =")
    for line in text.splitlines():
        esc = line.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'    "{esc}\\n"')
    lines.append(";")
    lines.append("")

def main():
    lines = ["/* Generated by tools/compile_shaders.py from src/gfx/shaders. Do not edit. */",
             f"/* sources sha256: {sources_hash()} */",
             "#pragma once", "#include <stddef.h>", "#include <stdint.h>", ""]
    for name in sorted(os.listdir(SRC)):
        if not name.endswith((".vert", ".frag")):
            continue
        path = os.path.join(SRC, name)
        emit(lines, name.replace(".", "_"), compile_one(path, []))
        for ident, defines in VARIANTS.get(name, []):
            emit(lines, ident, compile_one(path, defines))
        if name in SOURCES:
            emit_source(lines, SOURCES[name], open(path).read())
    open(OUT, "w").write("\n".join(lines))
    print("wrote", OUT)

if __name__ == "__main__":
    sys.exit(main())
