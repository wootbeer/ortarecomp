#!/usr/bin/env python3
"""Regenerate src/hle/d3d_calltrace.c: one tracing entry hook per Direct3D
function the game calls (minus those we replace outright).

Run after tools/recomp.py, from the repository root. Reads only the
disassembly and generated code in build/ and gen/ (never committed); writes
addresses, XDK API names and argument sizes, which are facts about the
binary. Names come from the output of Cxbx-Reloaded's XbSymbolDatabase CLI
for the player's own XBE (--symbols FILE, lines "D3D8__Name = 0x..."); without
it the hooks are named "?".
"""
import argparse, json, os, re, glob, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# The D3D section, and the end of game code (.text, before MMATRIX).
D3D_LO, D3D_HI, GAME_HI = 0x002AD9A0, 0x002C0A30, 0x002AC080


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--symbols", help="XbSymbolDatabase CLI output for this XBE")
    args = ap.parse_args()

    names = {}
    if args.symbols:
        for line in open(args.symbols):
            m = re.match(r"\s*D3D8?X?__(\w+)\s*=\s*0x([0-9a-fA-F]+)", line)
            if m:
                names.setdefault(int(m.group(2), 16), m.group(1))

    funcs = json.load(open(os.path.join(ROOT, "build/recomp-work/disasm/functions.json")))
    by = {int(f["start"], 16): f for f in funcs}
    called = set()
    for a, f in by.items():
        if a < GAME_HI:
            for c in f.get("calls_to", []):
                t = int(c, 16) if isinstance(c, str) else c
                if D3D_LO <= t < D3D_HI and t in by:
                    called.add(t)

    src = {}
    for p in glob.glob(os.path.join(ROOT, "gen/recomp_0*.c")):
        text = open(p).read()
        for m in re.finditer(r"^void (\w+_([0-9A-F]{8}))\(void\)\n\{(.*?)^\}", text, re.S | re.M):
            src[int(m.group(2), 16)] = m.group(3)

    # Replaced outright in src/guest/: an entry hook would never run. Hooked
    # by hand already: that hook does the tracing (one per address).
    replaced = set()
    for p in glob.glob(os.path.join(ROOT, "src/**/*.c"), recursive=True):
        if os.path.basename(p) == "d3d_calltrace.c":
            continue
        for m in re.finditer(r"^void sub_([0-9A-F]{8})(?:_enter)?\(void\)", open(p).read(), re.M):
            replaced.add(int(m.group(1), 16))

    out = [
        "/*",
        " * Generated by tools/gen_d3d_calltrace.py: a tracing hook on every Direct3D",
        " * entry point the game calls, with its argument count from the original's",
        " * `ret N`. Logging is off unless PDO_D3D_TRACE is set (see d3d_hle.c).",
        " */",
        "",
        "#include <stdint.h>",
        "",
        "void d3d_trace_call(uint32_t va, const char *name, int args);",
        "",
    ]
    for t in sorted(called - replaced):
        body = src.get(t, "")
        n = max([int(r or 0) for r in re.findall(r"/\* ret ?(\d*) \*/", body)] or [0]) // 4
        name = names.get(t, "?")
        out.append(f'void sub_{t:08X}_enter(void) {{ d3d_trace_call(0x{t:08X}u, "{name}", {n}); }}')
    open(os.path.join(ROOT, "src/hle/d3d_calltrace.c"), "w").write("\n".join(out) + "\n")
    print(f"{len(called - replaced)} hooks")


if __name__ == "__main__":
    sys.exit(main())
